def latest_notices(count: int = 3) -> list[dict]:
    """메인 화면에 보여줄 최신 공지."""
    return NOTICES[:count]


def find_notice(no: int) -> dict | None:
    """공지 한 건. 없으면 None."""
    for notice in NOTICES:
        if notice["no"] == no:
            return notice
    return None


def search_notices(keyword: str = "") -> list[dict]:
    """제목·본문에 키워드가 들어간 공지. 키워드가 없으면 전체."""
    keyword = (keyword or "").strip()
    if not keyword:
        return list(NOTICES)
    needle = keyword.lower()
    return [
        notice
        for notice in NOTICES
        if needle in notice["title"].lower()
        or any(needle in paragraph.lower() for paragraph in notice["body"])
    ]


def neighbours(no: int) -> tuple[dict | None, dict | None]:
    """공지 상세의 이전(최신)·다음(과거) 글."""
    for index, notice in enumerate(NOTICES):
        if notice["no"] == no:
            newer = NOTICES[index - 1] if index > 0 else None
            older = NOTICES[index + 1] if index + 1 < len(NOTICES) else None
            return newer, older
    return None, None
